"""
The content of the Tx Power Adjustment Table file is as follow:
    _______________________________________________
   |            text_message                       |
   |            (64bytes)                          |
   |_______________________________________________|
   |            Magic bytes(4 bytes)               |
   |_______________________________________________|
   |     rates                                     |
   |           CCK_1_2M (14 bytes)                 |
   |           CCK_5_11M (14 bytes)                |
   |           OFDM_6_9M (14 bytes)                |
   |           OFDM_12_18M (14 bytes)              |
   |           OFDM_24_36M (14 bytes)              |
   |           OFDM_48M (14 bytes)                 |
   |           OFDM_54M (14 bytes)                 |
   |           MCS_0_8 (14 bytes)                  |
   |           MCS_32 (14 bytes)                   |
   |           MCS_1_2_9_10 (14 bytes)             |
   |           MCS_3_4_11_12 (14 bytes)            |
   |           MCS_5_13 (14 bytes)                 |
   |           MCS_6_14 (14 bytes)                 |
   |           MCS_7_15 (14 bytes)                 |
   |_______________________________________________|
   |     bandwidths                                |
   |     40MHz vs 20MHz tx power offset (14 bytes) |
   |_______________________________________________|

* text_message is a ascii string that will be printed as info when loading the file by the driver.
* Magic bytes are hex values, only for validating the content of the file.
* rates and bandwidths are 8bit signed values. 0xFF means -1, 
*  0xFA means -6,  ... 0x80 means -128.
"""


class TxPowerAdjust:
    def __init__(self, country_code, rates, bandwidths):
        self.country_code = country_code
        self.rates = rates
        self.bandwidths = bandwidths

    def get_filename(self):
        if self.country_code == "00":
            return "mt7603e_txpat.bin"
        else:
            return f"mm_region_{self.country_code}_mt7603e_txpat.bin"

    def write(self, output):
        msg = f"MT7603E TX Power Adjustment Table V1.0 ({self.country_code})"
        output.write(msg.encode("ascii").ljust(64, b"\x00"))
        self._write_row([0xA0, 0xF0, 0xA1, 0xF1], "B", output)
        for row in self.rates:
            self._write_row(row, "b", f)
        self._write_row(self.bandwidths, "b", f)  # bw table

    @staticmethod
    def _write_row(row, typecode, output):
        row_array = array.array(typecode, row)
        row_array.tofile(output)


